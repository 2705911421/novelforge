def resolve_genre_key(value: object) -> Optional[str]:
    """Resolve a legacy key, display name, or stable id to a catalog key."""
    if not isinstance(value, str):
        return None
    candidate = value.strip()
    if not candidate or candidate == "自定义":
        return None
    return GENRE_ALIASES.get(candidate)


def get_genre_profile(value: object) -> Optional[dict]:
    key = resolve_genre_key(value)
    return GENRE_RULES.get(key) if key else None


def genre_contract_lines(value: object) -> list[str]:
    """Render the complete genre contract for planning and generation prompts."""
    profile = get_genre_profile(value)
    if not profile:
        return []
    planning = profile.get("planning") or {}
    limits = profile.get("limits") or {}
    lines = [
        f"题材核心承诺：{planning.get('core_promise', '')}",
        f"题材结构：{planning.get('structure', [])}",
        f"章节模板：{planning.get('chapter_template', [])}",
        f"节奏约束：{planning.get('pacing', {})}",
        f"必须追踪：{planning.get('must_track', [])}",
        f"连续创作检查：{planning.get('continuation_checks', [])}",
    ]
    lines.extend(f"题材硬限制：{item}" for item in limits.get("hard", []))
    lines.extend(f"题材审查门槛：{item}" for item in limits.get("review_gates", []))
    lines.extend(f"题材禁忌：{item}" for item in profile.get("taboos", []))
    return lines


# ========== 规则编译器 ==========

@dataclass
class CompiledRules:
    """编译后的规则集"""
    universal_rules: list = field(default_factory=list)
    genre_rules: list = field(default_factory=list)
    book_rules: list = field(default_factory=list)
    chapter_rules: list = field(default_factory=list)
    total_count: int = 0

    def get_all_rules(self) -> list:
        """获取所有规则（按优先级排列）"""
        rules = []
        rules.extend(self.chapter_rules)    # 最高优先级
        rules.extend(self.book_rules)
        rules.extend(self.genre_rules)
        rules.extend(self.universal_rules)  # 最低优先级
        return rules

    def format_for_prompt(self) -> str:
        """格式化为提示词"""
        parts = []
        if self.chapter_rules:
            parts.append("## 本章特定规则")
            for r in self.chapter_rules:
                parts.append(f"- {r}")
        if self.book_rules:
            parts.append("## 本书规则")
            for r in self.book_rules:
                parts.append(f"- {r}")
        if self.genre_rules:
            parts.append("## 题材规则")
            for r in self.genre_rules:
                parts.append(f"- {r}")
        if self.universal_rules:
            parts.append("## 通用创作规则")
            for r in self.universal_rules:
                parts.append(f"- {r}")
        return "\n".join(parts)


class WritingRules:
    """创作规则管理器"""

    def __init__(self):
        self.universal_rules = UNIVERSAL_RULES
        self.genre_rules = GENRE_RULES

    def compile_rules(self, genre: str = "", book_rules: Optional[list] = None,
                      chapter_rules: Optional[list] = None) -> CompiledRules:
        """编译规则集

        Args:
            genre: 题材
            book_rules: 书级规则
            chapter_rules: 章节级规则

        Returns:
            CompiledRules 编译后的规则集
        """
        compiled = CompiledRules()

        # 1. 通用规则
        compiled.universal_rules = [r["rule"] for r in self.universal_rules]

        # 2. 题材规则
        genre_key = resolve_genre_key(genre)
        if genre_key and genre_key in self.genre_rules:
            genre_data = self.genre_rules[genre_key]
            compiled.genre_rules = genre_contract_lines(genre_key) + [
                r["rule"] for r in genre_data["rules"]
            ]

        # 3. 书级规则
        if book_rules:
            compiled.book_rules = book_rules

        # 4. 章节级规则
        if chapter_rules:
            compiled.chapter_rules = chapter_rules

        compiled.total_count = (len(compiled.universal_rules) + len(compiled.genre_rules) +
                               len(compiled.book_rules) + len(compiled.chapter_rules))

        return compiled

    def get_genre_taboos(self, genre: str) -> list:
        """获取题材禁忌"""
        genre_key = resolve_genre_key(genre)
        if genre_key and genre_key in self.genre_rules:
            return self.genre_rules[genre_key].get("taboos", [])
        return []

    def get_rule_categories(self) -> list:
        """获取规则分类"""
        categories = set()
        for rule in self.universal_rules:
            categories.add(rule["category"])
        return sorted(categories)

    def get_rules_by_category(self, category: str) -> list:
        """按分类获取规则"""
        return [r for r in self.universal_rules if r["category"] == category]
