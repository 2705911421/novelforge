def _genre_profile(
    name: str,
    code: str,
    description: str,
    tags: list[str],
    core_promise: str,
    structure: list[str],
    chapter_template: list[str],
    pacing: dict[str, object],
    must_track: list[str],
    limits: list[str],
    taboos: list[str],
    rule_specs: list[tuple[str, str, list[str]]],
) -> dict:
    """Create a full genre contract shared by planning, writing, and review."""
    return {
        "id": code,
        "name": name,
        "description": description,
        "tags": tags,
        "planning": {
            "core_promise": core_promise,
            "structure": structure,
            "chapter_template": chapter_template,
            "pacing": {
                "chapter_end_required": True,
                "stagnation_threshold": 2,
                "transition_max_consecutive": 2,
                **pacing,
            },
            "must_track": must_track,
            "continuation_checks": [
                "本章目标是否改变了人物处境",
                "冲突是否产生了可追踪后果",
                "章末是否留下下一步主动问题",
            ],
        },
        "limits": {
            "hard": limits,
            "review_gates": [
                "不得违反已确认的世界规则、人物动机和时间线",
                "每个重大转折必须有源头、代价和后果",
                "不确定设定必须标记为待作者确认",
            ],
        },
        "rules": [
            {"id": f"{code}_{index:02d}", "name": title, "rule": rule, "check_points": checks}
            for index, (title, rule, checks) in enumerate(rule_specs, start=1)
        ],
        "taboos": taboos,
    }


